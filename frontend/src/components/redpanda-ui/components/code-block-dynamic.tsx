export type CodeBlockProps = HTMLAttributes<HTMLElement> & {
  /** A string value is treated as the icon's HTML. */
  icon?: ReactNode;
  /** @defaultValue true */
  allowCopy?: boolean;
  /** Keep the background color generated by Shiki/Rehype Code. @defaultValue false */
  keepBackground?: boolean;
  /**
   * Variant for the floating (no-title) copy button. Defaults to `'current-ghost'` when
   * `keepBackground` is set, `'ghost'` otherwise.
   */
  copyButtonVariant?: ButtonVariants['variant'];
  viewportProps?: HTMLAttributes<HTMLElement>;
  'data-line-numbers'?: boolean;
  /** @defaultValue 1 */
  'data-line-numbers-start'?: number;
  testId?: string;
  /**
   * Copy-button success callback. Named `onCopied` (not `onCopy`) because `CodeBlockProps`
   * extends `HTMLAttributes`, whose native clipboard `onCopy` collides at react-markdown
   * pre-props spread sites.
   */
  onCopied?: () => void;
};

export const Pre = forwardRef<HTMLPreElement, HTMLAttributes<HTMLPreElement>>(({ className, ...props }, ref) => (
  <pre className={cn('w-max min-w-full *:flex *:flex-col', className)} ref={ref} {...props}>
    {props.children}
  </pre>
));

Pre.displayName = 'Pre';

export const CodeBlock = forwardRef<HTMLElement, CodeBlockProps>(
  (
    {
      title,
      allowCopy = true,
      keepBackground = false,
      copyButtonVariant,
      icon,
      viewportProps,
      children,
      testId,
      onCopied,
      ...props
    },
    ref
    // biome-ignore lint/complexity/noExcessiveCognitiveComplexity: component requires multiple conditional rendering paths for title/copy/background
  ) => {
    const areaRef = useRef<HTMLDivElement>(null);
    const onCopy = () => {
      const preElement = areaRef.current?.getElementsByTagName('pre').item(0);
      if (!preElement) {
        return;
      }

      const clone = preElement.cloneNode(true) as HTMLElement;
      for (const node of Array.from(clone.querySelectorAll('.nd-copy-ignore'))) {
        node.replaceWith('\n');
      }

      // biome-ignore lint/complexity/noVoid: part of clipboard implementation
      void navigator.clipboard.writeText(clone.textContent ?? '').then(() => onCopied?.());
    };

    return (
      <figure
        dir="ltr"
        ref={ref}
        {...props}
        className={cn(
          'group relative my-4 overflow-hidden rounded-lg border bg-card text-body outline-none',
          props.className
        )}
        data-shiki-background={keepBackground || undefined}
        data-testid={testId}
      >
        {title ? (
          <div className="flex items-center gap-2 bg-surface-subtle px-4 py-1.5">
            {icon ? (
              <div
                className="text-subtle [&_svg]:size-3.5"
                // biome-ignore lint/security/noDangerouslySetInnerHtml: part of DynamicCodeBlock implementation
                // biome-ignore lint/security/noDangerouslySetInnerHtmlWithChildren: part of DynamicCodeBlock implementation
                dangerouslySetInnerHTML={
                  typeof icon === 'string'
                    ? {
                        __html: icon,
                      }
                    : undefined
                }
              >
                {typeof icon !== 'string' ? icon : null}
              </div>
            ) : null}
            <figcaption className="flex-1 truncate text-subtle">{title}</figcaption>
            {allowCopy ? <CopyButton className="-me-2" onCopy={onCopy} /> : null}
          </div>
        ) : (
          allowCopy && (
            <CopyButton
              className="absolute top-2 right-2 z-[2] backdrop-blur-md"
              onCopy={onCopy}
              variant={copyButtonVariant ?? (keepBackground ? 'current-ghost' : 'ghost')}
            />
          )
        )}
        <div
          ref={areaRef}
          {...viewportProps}
          className={cn(
            'max-h-[600px] overflow-auto py-3.5 text-body [&_.line]:px-4',
            props['data-line-numbers'] && '[&_.line]:pl-3',
            viewportProps?.className
          )}
          style={{
            counterSet: props['data-line-numbers']
              ? `line ${Number(props['data-line-numbers-start'] ?? 1) - 1}`
              : undefined,
            ...viewportProps?.style,
          }}
        >
          {children}
        </div>
      </figure>
    );
  }
);

CodeBlock.displayName = 'CodeBlock';

function CopyButton({
  className,
  onCopy,
  variant = 'ghost',
  ...props
}: ComponentProps<'button'> & {
  onCopy: () => void;
  variant?: ButtonVariants['variant'];
}) {
  const [checked, onClick] = useCopyButton(onCopy);

  return (
    <button
      aria-label={checked ? 'Copied Text' : 'Copy Text'}
      className={cn(
        buttonVariants({
          variant,
          size: 'sm',
        }),
        '[&_svg]:size-3.5',
        className
      )}
      onClick={onClick}
      type="button"
      {...props}
    >
      <Check className={cn('transition-transform motion-reduce:transition-none', !checked && 'scale-0')} />
      <Copy className={cn('absolute transition-transform motion-reduce:transition-none', checked && 'scale-0')} />
    </button>
  );
}

function pre(props: ComponentProps<'pre'> & SharedProps & { keepBackground?: boolean }) {
  const { keepBackground, ...rest } = props;
  return (
    <CodeBlock {...rest} className={cn('my-0', rest.className)} keepBackground={keepBackground} testId={rest.testId}>
      <Pre>{rest.children}</Pre>
    </CodeBlock>
  );
}

/** One Shiki theme per app theme, matching `use-shiki`, `code-editor` and `code-tabs`. */
export const DEFAULT_THEMES = { light: 'github-light', dark: 'github-dark-default' } as const;

/** For a block that stays a terminal in both app themes. Pair with `keepBackground`. */
export const TERMINAL_THEMES = { light: 'github-dark-default', dark: 'github-dark-default' } as const;

/**
 * Shiki dual-theme CSS, embedded so the component works without fumadocs CSS imports. Shiki emits a
 * custom property per theme rather than a token, so CSS picks the side rather than a `dark:` class.
 */
export const shikiDualThemeStyles = `
.shiki code span { color: var(--shiki-light); }
[data-shiki-background] { background-color: var(--shiki-light-bg); }
[data-theme='dark'] .shiki code span,
.dark .shiki code span { color: var(--shiki-dark); }
[data-theme='dark'] [data-shiki-background],
.dark [data-shiki-background] { background-color: var(--shiki-dark-bg); }
`;

// ElementType tag avoids React 18 type errors on the React 19 style-hoisting props.
const StyleResource = 'style' as ElementType;

export function DynamicCodeBlock({
  lang,
  code,
  options,
  testId,
  keepBackground,
}: {
  lang: string;
  code: string;
  options?: Omit<HighlightOptionsCommon, 'lang'> & HighlightOptionsThemes;
  testId?: string;
  /** Keep the shiki theme's own background instead of the registry's `bg-card`. Required for dark themes. */
  keepBackground?: boolean;
}) {
  const components: HighlightOptionsCommon['components'] = {
    pre: (props: ComponentProps<'pre'>) => pre({ ...props, testId, keepBackground }),
    ...options?.components,
  };

  // biome-ignore lint/correctness/useExhaustiveDependencies: initial value only
  const loading = useMemo(() => {
    const PreComponent = (components.pre ?? 'pre') as 'pre';
    const CodeComponent = (components.code ?? 'code') as 'code';

    return (
      <PreComponent>
        <CodeComponent>
          {code.split('\n').map((line, i) => (
            // biome-ignore lint/suspicious/noArrayIndexKey: part of DynamicCodeBlock implementation
            <span className="line" key={i}>
              {line}
            </span>
          ))}
        </CodeComponent>
      </PreComponent>
    );
  }, []);

  const highlighted = useShiki(code, {
    lang,
    loading,
    withPrerenderScript: true,
    ...options,
    components,
  });

  return (
    <>
      <StyleResource href="shiki-dual-theme" precedence="medium">
        {shikiDualThemeStyles}
      </StyleResource>
      {highlighted}
    </>
  );
}

// Statically bundled grammars let the highlighter run synchronously (no WASM/dynamic import) so SyncCodeBlock
// renders highlighted on first paint. Imports are side-effect-free, so DynamicCodeBlock-only consumers tree-shake them.
const SYNC_LANGS = [bash, go, java, javascript, json, python, sql, tsx, typescript, yaml];

let syncHighlighter: HighlighterCore | null = null;
function getSyncHighlighter(): HighlighterCore {
  if (!syncHighlighter) {
    syncHighlighter = createHighlighterCoreSync({
      engine: createJavaScriptRegexEngine(),
      themes: [githubLight, githubDarkDefault],
      langs: SYNC_LANGS,
    });
  }
  return syncHighlighter;
}

export type SyncCodeBlockProps = {
  code: string;
  lang: string;
  /**
   * One Shiki theme per app theme, defaulting to the pair every other code component uses. A block
   * that should read as a terminal in both points *both* slots at a dark Shiki theme and sets
   * `keepBackground` — see `TERMINAL_THEMES`. Without it, a near-white foreground lands on the card
   * at 1.18:1.
   */
  themes?: { light: string; dark: string };
} & Pick<
  CodeBlockProps,
  | 'keepBackground'
  | 'copyButtonVariant'
  | 'title'
  | 'icon'
  | 'allowCopy'
  | 'testId'
  | 'className'
  | 'viewportProps'
  | 'onCopied'
>;

// Synchronous variant of DynamicCodeBlock: highlights during render (no async/skeleton/flash). Trade-off:
// languages are fixed at build time (SYNC_LANGS) and ship in the bundle; use DynamicCodeBlock for arbitrary langs.
export function SyncCodeBlock({
  code,
  lang,
  themes = DEFAULT_THEMES,
  keepBackground,
  ...rest
}: SyncCodeBlockProps): ReactNode {
  const highlighter = getSyncHighlighter();
  const resolvedLang = highlighter.getLoadedLanguages().includes(lang) ? lang : 'text';

  const hast = highlighter.codeToHast(code, { lang: resolvedLang, themes, defaultColor: false });

  const rendered = toJsxRuntime(hast, {
    Fragment,
    jsx,
    jsxs,
    components: {
      // Shiki's pre props (.shiki class + --shiki-*-bg vars) go on the figure so keepBackground resolves.
      pre: ({ children, className, ...preProps }: ComponentProps<'pre'>) => (
        <CodeBlock {...preProps} {...rest} className={cn(className, rest.className)} keepBackground={keepBackground}>
          <Pre>{children}</Pre>
        </CodeBlock>
      ),
    },
  });

  return (
    <>
      <style>{shikiDualThemeStyles}</style>
      {rendered}
    </>
  );
}
