import consolePolicy from './oxlint.policy.json' with { type: 'json' };

function policyLevels(rules: Record<string, string | undefined>): Record<string, 'off' | 'error'> {
  const result: Record<string, 'off' | 'error'> = {};
  for (const [name, level] of Object.entries(rules)) {
    if (level !== 'off' && level !== 'error') {
      throw new Error(`Unsupported Console policy severity: ${name}`);
    }
    result[name] = level;
  }
  return result;
}

